#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const cssLayers=[['dkts.legacy','web/ui/legacy.css'],['dkts.tokens','web/ui/tokens.css'],['dkts.structure','web/ui/layout.css'],['dkts.components','web/ui/components.css'],['dkts.measurement','web/ui/measurement.css'],['dkts.platform','web/ui/responsive.css']];
function buildUiSystem({write=true}={}){
 const css=['/* Generated by tools/build-ui-system.cjs. Edit web/ui/*.css instead. */','@layer '+cssLayers.map(row=>row[0]).join(', '),...cssLayers.map(([layer,relative])=>'@layer '+layer+' {\n'+fs.readFileSync(path.join(root,relative),'utf8').trim()+'\n}')].join('\n\n')+'\n';
 const runtime=fs.readFileSync(path.join(root,'web/ui/runtime.js'),'utf8').trim(),app=fs.readFileSync(path.join(root,'web/app-main.js'),'utf8').trim();
 const js=['/* Generated by tools/build-ui-system.cjs. Edit web/ui/runtime.js and web/app-main.js instead. */',runtime,';',app,''].join('\n');
 if(write){fs.writeFileSync(path.join(root,'web/styles.css'),css,'utf8');fs.writeFileSync(path.join(root,'web/app.js'),js,'utf8');}
 return Object.freeze({css,js});
}
if(require.main===module){const out=buildUiSystem();process.stdout.write('Built DKTS UI Contract 1.0.0: '+Buffer.byteLength(out.js)+' bytes JS, '+Buffer.byteLength(out.css)+' bytes CSS\n');}
module.exports={buildUiSystem,cssLayers};
