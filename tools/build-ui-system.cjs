#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
/* Roll back the unverified layered UI redesign. The a97 visual contract is the
   authoritative baseline until keyboard/dropdown interaction is revalidated. */
const cssSources=[['a97-baseline','web/ui/legacy.css'],['control-alignment','web/ui/controls-alignment.css']];
function buildUiSystem({write=true}={}){
 const css=['/* Generated by tools/build-ui-system.cjs. a97 visual baseline plus targeted alignment. */',
  ...cssSources.map(([name,relative])=>'/* '+name+' */\n'+fs.readFileSync(path.join(root,relative),'utf8').trim())].join('\n\n')+'\n';
 const runtime=fs.readFileSync(path.join(root,'web/ui/runtime.js'),'utf8').trim(),app=fs.readFileSync(path.join(root,'web/app-main.js'),'utf8').trim();
 const js=['/* Generated by tools/build-ui-system.cjs. Edit web/ui/runtime.js and web/app-main.js instead. */',runtime,';',app,''].join('\n');
 if(write){fs.writeFileSync(path.join(root,'web/styles.css'),css,'utf8');fs.writeFileSync(path.join(root,'web/app.js'),js,'utf8');}
 return Object.freeze({css,js});
}
if(require.main===module){const out=buildUiSystem();process.stdout.write('Built DKTS a97-stable UI: '+Buffer.byteLength(out.js)+' bytes JS, '+Buffer.byteLength(out.css)+' bytes CSS\n');}
module.exports={buildUiSystem,cssSources};
