'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const {parseWaveformText,validateWaveform}=require('../src/controller/waveform.cjs');
test('arbitrary waveform is a non-executable plan with exact input values',()=>{
  const w=parseWaveformText('# time(s),voltage(V)\n0,0\n0.00000002,1\n0.00000004,-1\n');
  assert.equal(w.points.length,3);
  assert.equal(w.points[1].timeS,2e-8);
  assert.equal(w.durationS,4e-8);
  assert.equal(w.executable,false);
  assert.equal(w.hardwareVerified,false);
});
test('waveform rejects duplicate/reverse time and out-of-plan voltage',()=>{
  assert.throws(()=>parseWaveformText('0 0\n0 1'),/严格递增/);
  assert.throws(()=>parseWaveformText('1 0\n0.5 1'),/严格递增/);
  assert.throws(()=>validateWaveform([{timeS:0,voltageV:0},{timeS:1,voltageV:211}]),/规划范围/);
  assert.throws(()=>validateWaveform([{timeS:0,voltageV:0},{timeS:1,voltageV:41}],{sourceType:'pmu',loadOhms:1000000,rangeV:40}),/规划范围/);
  assert.throws(()=>validateWaveform([{timeS:0,voltageV:0},{timeS:1,voltageV:21}],{sourceType:'pmu',loadOhms:50,rangeV:40}),/规划范围/);
  const fiftyOhm=validateWaveform([{timeS:0,voltageV:0},{timeS:1,voltageV:20}],{sourceType:'pmu',loadOhms:50,rangeV:40});
  assert.equal(fiftyOhm.maxVoltageV,20);
  assert.equal(fiftyOhm.maxCurrentA,0.4);
  const highZ=validateWaveform([{timeS:0,voltageV:0},{timeS:1,voltageV:39.99}],{sourceType:'pmu',loadOhms:1000000,rangeV:40});
  assert(highZ.maxVoltageV>39.99);
  assert.throws(()=>validateWaveform([{timeS:0,voltageV:0},{timeS:1,voltageV:0.8}],{sourceType:'pgu',loadOhms:1,rangeV:40}),/规划范围/);
  assert.equal(parseWaveformText('0 0\n1 0.78',{sourceType:'pgu',loadOhms:1,rangeV:40}).maxVoltageV<0.8,true);
  assert.throws(()=>parseWaveformText('0 0\n1 1',{sourceType:'pgu'}),/负载阻值/);
  assert.throws(()=>validateWaveform([{timeS:0,voltageV:0},{timeS:1,voltageV:5.1}],{sourceType:'pgu',loadOhms:50,rangeV:10}),/规划范围/);
  assert.equal(validateWaveform([{timeS:0,voltageV:0},{timeS:1,voltageV:5}],{sourceType:'pgu',loadOhms:50,rangeV:10}).maxVoltageV,5);
  assert.throws(()=>parseWaveformText('0 0'),/至少需要 2 个/);
});
