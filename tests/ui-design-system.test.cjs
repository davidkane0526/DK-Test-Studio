'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const {buildUiSystem,cssLayers}=require('../tools/build-ui-system.cjs');
test('compiled UI resources are deterministic products of modular sources',()=>{
 const out=buildUiSystem({write:false});assert.equal(read('web/app.js'),out.js);assert.equal(read('web/styles.css'),out.css);
 assert.match(out.js,/VERSION='1.0.0'/);assert.match(out.css,/Generated by tools\/build-ui-system\.cjs/);assert.equal(cssLayers.length,6);
});
test('CSS ownership is explicit and ordered from legacy foundation to platform layout',()=>{
 const css=read('web/styles.css'),order=['dkts.legacy','dkts.tokens','dkts.structure','dkts.components','dkts.measurement','dkts.platform'];let previous=-1;
 for(const layer of order){const i=css.indexOf(layer);assert(i>previous,layer+' must follow previous layer');previous=i;}
 assert.match(css,/--dkui-canvas/);assert.match(css,/--dkui-control-border/);assert.match(css,/\.sweep-axis-heading/);assert.match(css,/@container dkts-workspace/);assert.doesNotMatch(css,/DKDS-aligned compact workspace/);
});
test('runtime exposes DKDS semantic identities, reusable controls and common metrics',()=>{
 const source=read('web/ui/runtime.js');assert.match(source,/contractVersion:VERSION/);assert.match(source,/action:'toolbarAction'/);
 assert.match(source,/createField/);assert.match(source,/createAction/);assert.match(source,/createSurface/);assert.match(source,/desktopHeightPx:32,touchHeightPx:44/);
 assert.match(source,/dkdsComponentIdentity/);assert.match(source,/DKDSStyleGate/);assert.match(source,/applyThemeSnapshot/);
});
test('DKDS plugin forwards host theme and declares the theme dependency',()=>{
 const presentation=read('integrations/dkds/presentation.js'),bridge=read('integrations/dkds/frame-bridge.js'),manifest=JSON.parse(read('integrations/dkds/plugin.json'));
 assert.match(presentation,/DKDSTheme/);assert.match(presentation,/tokens\?\.\(\)/);assert.match(presentation,/type:'theme'/);assert.match(bridge,/DKTSFrameSession/);assert(manifest.requiresCore.includes('ui.theme'));
});
test('hot-update resource set remains compatible with existing native shells',()=>{
 const builder=read('tools/build-ui-bundle.cjs'),updater=read('src/ui-update.cjs'),android=read('android/app/src/main/java/studio/dk/test/UiUpdateManager.java');
 assert.match(builder,/index\.html/);assert.match(builder,/app\.js/);assert.match(builder,/styles\.css/);
 assert.match(updater,/index\.html[\s\S]*app\.js[\s\S]*styles\.css/);
 assert.match(android,/index\.html[\s\S]*app\.js[\s\S]*styles\.css/);
 assert.match(read('docs/UI_ARCHITECTURE.md'),/three-file set/);
});
